#!/bin/bash
set -e

# Disco Incognito - Development server script
# Usage: ./run.sh [--detached] [--stop] [--test]

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE_FILE="$SCRIPT_DIR/.run.ports"
STATE_FILE_TEST="$SCRIPT_DIR/.run.ports.test"

# Port ranges
MAIN_BACKEND_START=8000
MAIN_FRONTEND_START=3000
FEATURE_BACKEND_START=9000
FEATURE_FRONTEND_START=9100
PORT_SCAN_RANGE=100

# Test mode flag
TEST_MODE=false

# Check if a port is in use
is_port_in_use() {
    local port=$1
    # Check Docker containers
    if docker ps --format '{{.Ports}}' 2>/dev/null | grep -q ":${port}->"; then
        return 0
    fi
    # Check other processes
    if command -v lsof >/dev/null 2>&1; then
        if lsof -i:"$port" >/dev/null 2>&1; then
            return 0
        fi
    elif command -v ss >/dev/null 2>&1; then
        if ss -tuln | grep -q ":${port} "; then
            return 0
        fi
    fi
    return 1
}

# Find next available port starting from given port
find_available_port() {
    local start_port=$1
    local port=$start_port
    local max_port=$((start_port + PORT_SCAN_RANGE))

    while [ $port -lt $max_port ]; do
        if ! is_port_in_use "$port"; then
            echo "$port"
            return 0
        fi
        port=$((port + 1))
    done

    echo "ERROR: No available port found in range $start_port-$max_port" >&2
    return 1
}

# Get the current git branch
get_current_branch() {
    git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "unknown"
}

# Determine if we're on the main branch
is_main_branch() {
    local branch
    branch=$(get_current_branch)
    [[ "$branch" == "main" || "$branch" == "master" ]]
}

# Get the state file for current mode
get_state_file() {
    if [ "$TEST_MODE" = true ]; then
        echo "$STATE_FILE_TEST"
    else
        echo "$STATE_FILE"
    fi
}

# Read ports from state file
read_saved_ports() {
    local state_file
    state_file=$(get_state_file)

    if [ -f "$state_file" ]; then
        # Source the file to get BACKEND_PORT and FRONTEND_PORT
        # shellcheck source=/dev/null
        source "$state_file"
        echo "$BACKEND_PORT $FRONTEND_PORT"
    else
        echo ""
    fi
}

# Save ports to state file
save_ports() {
    local backend_port=$1
    local frontend_port=$2
    local state_file
    state_file=$(get_state_file)

    cat > "$state_file" << EOF
# Port assignments for this worktree (auto-generated by run.sh)
BACKEND_PORT=$backend_port
FRONTEND_PORT=$frontend_port
EOF
}

# Determine ports to use
determine_ports() {
    local backend_start frontend_start
    local backend_port frontend_port

    # Set starting ports based on branch
    if is_main_branch && [ "$TEST_MODE" = false ]; then
        backend_start=$MAIN_BACKEND_START
        frontend_start=$MAIN_FRONTEND_START
    else
        backend_start=$FEATURE_BACKEND_START
        frontend_start=$FEATURE_FRONTEND_START
    fi

    # Try to reuse saved ports first
    local saved_ports
    saved_ports=$(read_saved_ports)

    if [ -n "$saved_ports" ]; then
        local saved_backend saved_frontend
        read -r saved_backend saved_frontend <<< "$saved_ports"

        # Check if saved backend port is still available
        if ! is_port_in_use "$saved_backend"; then
            backend_port=$saved_backend
        else
            echo "Saved backend port $saved_backend is in use, finding new port..." >&2
            backend_port=$(find_available_port "$backend_start")
        fi

        # Check if saved frontend port is still available
        if ! is_port_in_use "$saved_frontend"; then
            frontend_port=$saved_frontend
        else
            echo "Saved frontend port $saved_frontend is in use, finding new port..." >&2
            frontend_port=$(find_available_port "$frontend_start")
        fi
    else
        # No saved ports, find new ones
        backend_port=$(find_available_port "$backend_start")
        frontend_port=$(find_available_port "$frontend_start")
    fi

    # Save the ports for next time
    save_ports "$backend_port" "$frontend_port"

    echo "$backend_port $frontend_port"
}

show_help() {
    echo "Usage: ./run.sh [OPTIONS]"
    echo ""
    echo "Options:"
    echo "  --detached    Run containers in background"
    echo "  --stop        Stop running containers"
    echo "  --test        Use test mode ports (9000+ range)"
    echo "  --help        Show this help message"
    echo ""
    echo "Port Assignment:"
    echo "  Main branch:    Backend 8000+, Frontend 3000+"
    echo "  Feature branch: Backend 9000+, Frontend 9100+"
    echo ""
    echo "Ports are saved to .run.ports and reused on subsequent runs."
}

start_containers() {
    local detached=$1
    local ports
    ports=$(determine_ports)

    local backend_port frontend_port
    read -r backend_port frontend_port <<< "$ports"

    export PORT=$backend_port
    export VITE_PORT=$frontend_port
    export VITE_API_URL="http://localhost:$backend_port"
    export SPOTIFY_REDIRECT_URI="http://localhost:$backend_port/api/auth/callback"

    local branch
    branch=$(get_current_branch)

    echo "Starting Disco Incognito..."
    echo "  Branch:   $branch"
    echo "  Backend:  http://localhost:$backend_port"
    echo "  Frontend: http://localhost:$frontend_port"
    echo ""

    if [ "$detached" = true ]; then
        docker-compose -f docker-compose.dev.yml up -d --build
        echo ""
        echo "Running in background."
        echo "Run './run.sh --stop' to stop."
    else
        docker-compose -f docker-compose.dev.yml up --build
    fi
}

stop_containers() {
    echo "Stopping Disco Incognito..."
    docker-compose -f docker-compose.dev.yml down
    echo "Stopped."
}

# Parse arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        --test)
            TEST_MODE=true
            shift
            ;;
        --stop)
            stop_containers
            exit 0
            ;;
        --detached)
            start_containers true
            exit 0
            ;;
        --help)
            show_help
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
done

# Default: run attached
start_containers false
