#!/bin/bash

# Disco Incognito - Validation script

# Run before commits: linting, unit tests, E2E tests
# Usage: ./validate.sh [--fix] [--unit] [--e2e] [--backend]

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

RUN_ALL=true
RUN_FIX=false
RUN_UNIT=false
RUN_E2E=false
RUN_BACKEND=false

# Track failures
FAILED=0
FAILED_STEPS=""

for arg in "$@"; do
    case $arg in
        --fix)
            RUN_FIX=true
            ;;
        --unit)
            RUN_ALL=false
            RUN_UNIT=true
            ;;
        --e2e)
            RUN_ALL=false
            RUN_E2E=true
            ;;
        --backend)
            RUN_ALL=false
            RUN_BACKEND=true
            ;;
        --help)
            echo "Usage: ./validate.sh [OPTIONS]"
            echo ""
            echo "Options:"
            echo "  --fix       Auto-fix linting issues"
            echo "  --unit      Run only frontend unit tests"
            echo "  --e2e       Run only E2E tests"
            echo "  --backend   Run only backend tests"
            echo "  --help      Show this help message"
            echo ""
            echo "With no options, runs all tests."
            exit 0
            ;;
    esac
done

echo "=== Disco Incognito Validation ==="
echo ""

# Backend linting (Python/ruff)
if $RUN_ALL || $RUN_FIX; then
    echo ">>> Backend Linting (ruff)"
    if $RUN_FIX; then
        python run_linter.py --fix || true
    else
        if ! python run_linter.py; then
            echo "Backend linting failed. Run with --fix to auto-fix."
            FAILED=1
            FAILED_STEPS="$FAILED_STEPS backend-lint"
        fi
    fi
    echo ""
fi

# Frontend linting
if $RUN_ALL || $RUN_FIX; then
    echo ">>> Frontend Linting"
    cd frontend
    if $RUN_FIX; then
        npm run lint -- --fix || true
    else
        if ! npm run lint; then
            echo "Frontend linting failed. Run with --fix to auto-fix."
            FAILED=1
            FAILED_STEPS="$FAILED_STEPS frontend-lint"
        fi
    fi
    cd ..
    echo ""
fi

# Frontend unit tests
if $RUN_ALL || $RUN_UNIT; then
    echo ">>> Frontend Unit Tests"
    cd frontend
    if ! npm run test:unit; then
        FAILED=1
        FAILED_STEPS="$FAILED_STEPS frontend-unit"
    fi
    cd ..
    echo ""
fi

# Frontend E2E tests (starts own backend)
if $RUN_ALL || $RUN_E2E; then
    echo ">>> Frontend E2E Tests"

    # Read port from .run.ports (generated by run.sh)
    TEST_PORT=$(grep BACKEND_PORT .run.ports 2>/dev/null | cut -d= -f2)
    TEST_PORT=${TEST_PORT:-9000}

    # Start backend for E2E tests
    echo "Starting backend on port $TEST_PORT..."
    cd backend
    SESSION_STORAGE_FILE="$SCRIPT_DIR/data/disco_incognito.json" python -m uvicorn app.main:app --host 0.0.0.0 --port "$TEST_PORT" &
    BACKEND_PID=$!
    cd ..

    # Wait for backend to be ready
    for i in {1..30}; do
        if curl -s "http://localhost:$TEST_PORT/api/health" > /dev/null 2>&1; then
            echo "Backend ready on port $TEST_PORT"
            break
        fi
        sleep 0.5
    done

    # Run E2E tests with BACKEND_URL pointing to our test backend
    cd frontend
    if ! BACKEND_URL="http://localhost:$TEST_PORT" npm run test:e2e; then
        FAILED=1
        FAILED_STEPS="$FAILED_STEPS frontend-e2e"
    fi
    cd ..

    # Clean up backend
    echo "Stopping test backend..."
    kill $BACKEND_PID 2>/dev/null || true
    echo ""
fi

# Backend tests
if $RUN_ALL || $RUN_BACKEND; then
    echo ">>> Backend Tests"
    cd backend
    if ! python -m pytest -v; then
        FAILED=1
        FAILED_STEPS="$FAILED_STEPS backend-tests"
    fi
    cd ..
    echo ""
fi

echo "=== Validation Complete ==="
echo ""

if [ $FAILED -eq 0 ]; then
    echo "==========================================="
    echo "  ALL TESTS PASSED"
    echo "==========================================="
    exit 0
else
    echo "==========================================="
    echo "  VALIDATION FAILED"
    echo "  Failed steps:$FAILED_STEPS"
    echo "==========================================="
    exit 1
fi
